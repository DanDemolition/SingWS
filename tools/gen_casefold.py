#!/usr/bin/env python3
"""Generate rust/crates/singws-uimodel/src/casefold_table.rs: every character whose Python ``str.casefold()`` differs from its own per-character
``str.lower()``. Rust folds a character as its lowercase mapping unless it is listed here. Run with the Python the app ships, then re-run
tools/history_parity.py (its sweep proves the table against every code point)."""
import sys
from pathlib import Path

rows = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if c.casefold() != c.lower():
        rows.append((cp, c.casefold()))
out = Path(__file__).resolve().parent.parent / "rust/crates/singws-uimodel/src/casefold_table.rs"
lines = [f"// Generated by tools/gen_casefold.py with Python {sys.version.split()[0]} (Unicode {__import__('unicodedata').unidata_version}). Do not edit by hand.",
         "pub const CASEFOLD_EXCEPTIONS: &[(char, &str)] = &["]
for cp, folded in rows:
    esc = "".join(f"\\u{{{ord(ch):x}}}" for ch in folded)
    lines.append(f"    ('\\u{{{cp:x}}}', \"{esc}\"),")
lines.append("];")
out.write_text("\n".join(lines) + "\n")
print(f"{len(rows)} exceptions -> {out}")
